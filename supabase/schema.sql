-- Emmanuel Portfolio: Supabase/PostgreSQL schema
-- Run this file once in Supabase Dashboard -> SQL Editor.

create table if not exists public.profile (
  id smallint primary key default 1 check (id = 1),
  name text not null,
  role text not null,
  specialty text not null,
  location text not null,
  phone text not null,
  email text not null,
  intro text not null,
  bio text not null,
  availability text not null,
  positioning text not null,
  socials jsonb not null default '{}'::jsonb,
  highlights jsonb not null default '[]'::jsonb,
  growth_areas jsonb not null default '[]'::jsonb,
  opportunity_tracks jsonb not null default '[]'::jsonb,
  profile_image_url text,
  profile_image_path text,
  updated_at timestamptz not null default now()
);

alter table public.profile add column if not exists profile_image_url text;
alter table public.profile add column if not exists profile_image_path text;

create or replace function public.set_profile_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profile_updated_at on public.profile;
create trigger profile_updated_at
before update on public.profile
for each row execute function public.set_profile_updated_at();

insert into storage.buckets (id, name, public)
values ('portfolio-media', 'portfolio-media', true)
on conflict (id) do update set public = true;

create table if not exists public.experiences (
  id bigint generated by default as identity primary key,
  company text not null,
  role text not null,
  type text not null,
  period text not null,
  summary text not null default '',
  description text not null,
  tags jsonb not null default '[]'::jsonb,
  company_logo_url text,
  company_logo_path text,
  image_urls jsonb not null default '[]'::jsonb,
  image_paths jsonb not null default '[]'::jsonb,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (company, role)
);

alter table public.experiences add column if not exists summary text not null default '';
alter table public.experiences add column if not exists company_logo_url text;
alter table public.experiences add column if not exists company_logo_path text;
alter table public.experiences add column if not exists image_urls jsonb not null default '[]'::jsonb;
alter table public.experiences add column if not exists image_paths jsonb not null default '[]'::jsonb;

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  type text not null,
  description text not null,
  tags jsonb not null default '[]'::jsonb,
  link text not null default '',
  case_study text,
  accent text not null default 'blue',
  image_url text,
  image_path text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (title)
);

alter table public.projects add column if not exists image_url text;
alter table public.projects add column if not exists image_path text;

create table if not exists public.education (
  id bigint generated by default as identity primary key,
  qualification text not null,
  institution text not null,
  period text not null,
  detail text not null default '',
  sort_order integer not null default 0,
  unique (qualification)
);

create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  value text not null unique,
  category text not null default 'Other',
  sort_order integer not null default 0
);

alter table public.skills add column if not exists category text not null default 'Other';

create table if not exists public.certifications (
  id bigint generated by default as identity primary key,
  value text not null unique,
  sort_order integer not null default 0
);

create table if not exists public.languages (
  id bigint generated by default as identity primary key,
  value text not null unique,
  sort_order integer not null default 0
);

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.profile enable row level security;
